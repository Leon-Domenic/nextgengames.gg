export const DEFAULT_UNLOCKED_CHAR_IDS = [
  'hat', 'robot', 'kitten', 'pigeon', 'unicorn', 'modeer', 'fairydog',
];

export function getUnlockedCosmeticIds() {
  const base = new Set(DEFAULT_UNLOCKED_CHAR_IDS);
  if (typeof window !== 'undefined') {
    try {
      const stored = localStorage.getItem('ngg_unlocked_cosmetics');
      if (stored) {
        for (const id of JSON.parse(stored)) base.add(id);
      }
    } catch (e) {}
  }
  return base;
}

export function isCharacterUnlocked(char, unlockedSet = getUnlockedCosmeticIds()) {
  if (!char) return false;
  if ((char.priceCash || 0) === 0 && (char.priceCoins || 0) === 0) return true;
  return unlockedSet.has(char.id);
}

export function getAvailableCharacters() {
  const unlocked = getUnlockedCosmeticIds();
  return CHARACTERS.filter((c) => isCharacterUnlocked(c, unlocked));
}

export const CHARACTER_MAP = Object.fromEntries(
  CHARACTERS.map(c => [c.id, c])
);

export const TOKEN_ICONS = Object.fromEntries(
  CHARACTERS.map(c => [c.id, c.icon])
);

export const REACTION_STATES = ['pay', 'receive', 'negotiate', 'monopoly', 'bankrupt'];

const CHARACTER_ID_ALIASES = {
  rudolf: 'kitten',
  cantino: 'pigeon',
  rainbow_dash: 'unicorn',
};

export function resolveCanonicalCharacterId(avatarToken) {
  if (!avatarToken) return 'hat';
  const normalized = String(avatarToken).toLowerCase();
  const mapped = CHARACTER_ID_ALIASES[normalized] || normalized;
  return CHARACTER_MAP[mapped] ? mapped : 'hat';
}

export function getCharacterReactionSrc(avatarToken, state = 'pay') {
  const canonicalId = resolveCanonicalCharacterId(avatarToken);
  const safeState = REACTION_STATES.includes(state) ? state : 'pay';
  return `/reactions/${canonicalId}/${safeState}.png`;
}
