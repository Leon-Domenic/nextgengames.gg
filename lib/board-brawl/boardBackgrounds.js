export const BOARD_BACKGROUND_MAP = Object.fromEntries(
  BOARD_BACKGROUNDS.map(b => [b.id, b])
);

export function getBoardBackground(id) {
  if (!id) return BOARD_BACKGROUND_MAP[DEFAULT_BOARD_BACKGROUND_ID];
  return BOARD_BACKGROUND_MAP[id] || BOARD_BACKGROUND_MAP[DEFAULT_BOARD_BACKGROUND_ID];
}

export function getEquippedBoardBackgroundId() {
  if (typeof window !== 'undefined') {
    return localStorage.getItem('ngg_equipped_board_background') || DEFAULT_BOARD_BACKGROUND_ID;
  }
  return DEFAULT_BOARD_BACKGROUND_ID;
}
